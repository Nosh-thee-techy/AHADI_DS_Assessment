def set_lang(lang: str) -> str:
    global _LANG
    _LANG = lang if lang in PACKS else "en"
    return _LANG


def lang() -> str:
    return _LANG


def t(key: str, **kwargs) -> str:
    pack = PACKS.get(_LANG, EN)
    text = pack.get(key) or EN.get(key) or key
    if kwargs:
        return text.format(**kwargs)
    return text


def indicator_label(column: str) -> str:
    return t(f"indicator.{column}")
